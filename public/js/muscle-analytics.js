export const MUSCLE_GROUPS = [
  'Грудь','Спина','Широчайшие','Плечи','Передняя дельта','Средняя дельта','Задняя дельта',
  'Бицепс','Трицепс','Предплечья','Трапеции','Квадрицепсы','Бицепс бедра','Ягодицы','Икры',
  'Пресс','Косые мышцы живота'
];

export function getExerciseMuscleProfile(name, fallbackGroup = '') {
  const profile = PROFILES[String(name || '').trim()];
  if (profile) return { ...profile };
  const fallback = GROUP_FALLBACK[fallbackGroup];
  return fallback ? { ...fallback } : {};
}

export function getExerciseMuscleContributions(name, fallbackGroup = '') {
  return Object.entries(getExerciseMuscleProfile(name, fallbackGroup))
    .filter(([, coefficient]) => Number.isFinite(coefficient) && coefficient > 0)
    .map(([muscle, coefficient]) => ({
      muscle,
      coefficient,
      type: coefficient >= 0.75 ? 'direct' : 'indirect'
    }));
}
